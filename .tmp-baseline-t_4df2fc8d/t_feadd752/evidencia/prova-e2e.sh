#!/usr/bin/env bash
# Prova (2 partes) do ajuste:
#  A) passo banco_local REAL (bloco extraido dos dois scripts), ao vivo, sobre o banco local do conjunto,
#     com HOME de ensaio + fixture do registro (R1 proibe ler producao). Antes (hoje) x Depois (ajuste).
#  B) controle negativo minimo: diferenca NOVA criada pela migration do cartao continua debitada.
set -u
ED=/home/joaquim_ataides/hermes-workspaces/Zapp_Web_V2/.tmp-baseline-t_4df2fc8d/t_feadd752
EV=/home/joaquim_ataides/hermes-workspaces/Zapp_Web_V2/.tmp-baseline-t_4df2fc8d
E="$ED/evidencia"
NOME=v2-26100617458c7f
ST="$EV/home-ensaio/.local/share/zapp-local/stacks/$NOME/estado"
mkdir -p "$ST"

echo "######## A. passo banco_local REAL, antes x depois (registro legivel por fixture) ########"
run() { # run <bloco.sh> <arvore> <tag>
  echo "$2" > "$ST/copia.txt"
  HOME="$EV/home-ensaio" PATH="$EV/fixture-zapp-db-ler:$PATH" bash "$1" "$2" "$NOME" > "$E/e2e-$3.out" 2>&1
  local rc=$?
  printf -- '--- %s  rc=%s ---\n' "$3" "$rc"
  tail -6 "$E/e2e-$3.out"
  printf -- '--- fim %s ---\n\n' "$3"
}
run "$E/bloco-hoje.sh" "$EV/arvore-A" A-retrato-velho-hoje
run "$E/bloco-novo.sh" "$EV/arvore-A" A-retrato-velho-ajuste
run "$E/bloco-hoje.sh" "$EV/arvore-B" B-retrato-fresco-hoje
run "$E/bloco-novo.sh" "$EV/arvore-B" B-retrato-fresco-ajuste

echo "######## B. controle negativo (diferenca NOVA do cartao continua debitada) ########"
NEG="$E/negativo"
rm -rf "$NEG"; mkdir -p "$NEG/arvore/supabase/migrations" "$NEG/st"
cp -f "$EV/arvore-B/supabase/schema-manifest.json" "$NEG/arvore/supabase/schema-manifest.json"
cat > "$NEG/arvore/supabase/migrations/20990101000000_sonda_cartao.sql" <<'SQL'
-- fixture sintetica: migration PENDENTE do cartao
create table if not exists public.sonda_cartao (
  id bigint generated by default as identity primary key,
  col_citada text
);
SQL
: > "$NEG/st/falhas.tsv"
cat > "$NEG/st/check-diferencas.txt" <<'T'
indexes|sonda_cartao.sonda_cartao_pkey
columns|r:public.sonda_cartao.col_citada
functions|f:consume_gmail_oauth_state(p_user_id uuid, p_state text)
T
W="$NEG/arvore" ST="$NEG/st" NOVAS=20990101000000_sonda_cartao.sql python3 "$E/classifica.py" "$E/emb-novo.py" | tee "$E/negativo.out"
